def _build_fixed_targets(data: list) -> list:
    result = []
    for name, label, obj_type, category, ra, dec, size, mag in data:
        result.append({
            "name": name,
            "label": label,
            "type": obj_type,
            "category": category,
            "size_arcmin": size,
            "mag": mag,
            "coord": SkyCoord(ra=ra * u.deg, dec=dec * u.deg),
        })
    return result


